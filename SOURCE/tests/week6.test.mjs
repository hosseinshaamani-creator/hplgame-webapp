import test from 'node:test';
import assert from 'node:assert/strict';
import {learningOverview,personalHome,learningPaths} from '../lib/learning-home.js';
import {createApp,wait} from './support/auth-fixture.mjs';

test('week 6 overview selects unfinished projects and reports actual learning state',()=>{
  assert.deepEqual(learningOverview([]),{current:null,steps:0,total:0,completed:0});
  const games=[{id:'complete',idea:'دوز',step:3,won:true},{id:'practice',idea:'مار',step:3,won:false},{id:'new',idea:'پازل',step:1,won:false}];
  const state=learningOverview(games);
  assert.equal(state.current.id,'practice');
  assert.equal(state.steps,7);assert.equal(state.total,9);assert.equal(state.completed,1);
  const markup=personalHome({name:'<img>',games,composer:'<form></form>'});
  assert.ok(markup.includes('&lt;img&gt;'));assert.ok(markup.includes('data-open-game="practice"'));
  assert.equal(markup.includes('class="badge"'),false);
  assert.equal(learningPaths.length,5);
  const exercise=personalHome({name:'کاربر',games:[],composer:'',exercise:{id:'saved',title:'سفر ستاره'}});
  assert.match(exercise,/data-action="open-project" data-id="saved"/);
  assert.match(exercise,/سفر ستاره/);
});

test('week 6 home: choose, edit, validate, save, resume, rename, switch curriculum and restore after login',{timeout:20000},async t=>{
  const {w,q,login,navigate,tick,state,click,errors}=await createApp(t,{onboarding:true});
  w.HTMLCanvasElement.prototype.getContext=()=>new Proxy({},{get:()=>()=>{}});
  const submit=selector=>q(selector).dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(w.document.querySelectorAll('.side-nav a').length,4);
  assert.equal(q('.badge'),null);
  await navigate('learn');assert.equal(q('#auth-form'),null);
  q('[data-learning-path=numbers]').click();await wait(60);tick(1);
  assert.equal(w.location.hash,'#/');assert.match(q('#game-idea').value,/پازل اعداد/);
  assert.equal(w.document.activeElement,q('#game-idea'));
  q('#game-idea').value=' ';submit('#idea-form');assert.equal(q('#game-idea').getAttribute('aria-invalid'),'true');
  assert.equal(state.learning.length,0);
  await login();assert.equal(w.location.hash,'#/');assert.match(q('#next-title').textContent,/اولین/);
  q('[data-example]').click();assert.ok(q('#game-idea'));assert.equal(state.learning.length,0);
  q('#game-idea').value='دوز با دوستانم';submit('#idea-form');await wait(100);
  assert.match(q('[role=log]').textContent,/دوز با دوستانم/);
  q('[data-proto=next]').click();await wait(600);
  assert.equal(state.learning.length,1);assert.equal(state.learning[0].step,1);
  const id=state.learning[0].id;
  await navigate('');assert.equal(q('[data-open-game]').dataset.openGame,id);
  assert.match(q('.next-action').textContent,/کنترل‌ها/);assert.match(q('.home-progress').textContent,/۱ از ۳/);
  q('[data-edit-idea]').click();q('#proto-edit-idea').value=' ';submit('#proto-edit-form');
  assert.match(q('#proto-edit-error').textContent,/۲ تا ۶۰۰/);assert.equal(state.learning[0].idea,'دوز با دوستانم');
  q('#proto-edit-idea').value='دوز <img src=x> با دوستم';submit('#proto-edit-form');await wait(600);
  assert.equal(state.learning[0].step,1);assert.equal(q('.next-action img'),null);
  assert.equal(state.learning[0].id,id);assert.match(state.learning[0].messages[0].text,/<img/);
  state.offline=true;
  q('[data-edit-idea]').click();q('#proto-edit-idea').value='دوز برای تمرین با دوستان';submit('#proto-edit-form');await wait(600);
  assert.match(q('.proto-storage').textContent,/ذخیره انجام نشد/);assert.equal(q('#home-save-retry').hidden,false);
  assert.notEqual(state.learning[0].idea,'دوز برای تمرین با دوستان');
  state.offline=false;q('#home-save-retry').click();await wait(100);
  assert.equal(state.learning[0].idea,'دوز برای تمرین با دوستان');assert.equal(q('#home-save-retry').hidden,true);
  q('[data-edit-idea]').click();q('#proto-edit-idea').value='پازل اعداد';submit('#proto-edit-form');await wait(600);
  assert.equal(state.learning[0].step,0);assert.equal(state.learning[0].won,false);assert.equal(state.learning.length,1);
  q('[data-open-game]').click();await wait(70);assert.ok(q('[data-number="1"]'));
  q('[data-proto=new]').click();assert.ok(q('#proto-upgrade'));assert.equal(q('#proto-upgrade').disabled,true);q('[data-close]').click();
  click('logout');await wait(100);await login();await navigate('');
  assert.match(q('.next-action').textContent,/پازل اعداد/);assert.equal(q('[data-open-game]').dataset.openGame,id);
  q('#theme-toggle').click();assert.equal(w.document.documentElement.dataset.theme,'dark');assert.equal(q('.badge'),null);
  q('#theme-toggle').click();assert.equal(w.localStorage.getItem('hplgame-theme'),'light');
  await navigate('projects');assert.equal(q('[data-open-game]').dataset.openGame,id);
  assert.deepEqual(errors,[]);
});
